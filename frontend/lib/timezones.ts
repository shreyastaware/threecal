export type TimezoneOption = {
  label: string;
  value: string;
};

export const TIMEZONE_OPTIONS: readonly TimezoneOption[] = timezoneSource.map(
  ({ timezone, timeOffset }) => ({
    label: `${timezone} ${timeOffset}`,
    value: timezone,
  }),
);

const timezoneLabels = new Map(
  TIMEZONE_OPTIONS.map(({ label, value }) => [value, label]),
);

export function getTimezoneOptionLabel(timezone: string): string {
  return timezoneLabels.get(timezone) ?? timezone;
}
